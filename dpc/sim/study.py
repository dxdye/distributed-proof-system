"""Parameter study for the pilot (M3, concept §18; open decisions OD-5, OD-8).

Sweeps the honeypot share h, the PV threshold θ_PV and k_min, with and without
honeypot lookup attackers, and reports per configuration (mean over seeds):

* miss rate — erroneous items accepted / erroneous items (what δ_A protects),
* false errors — correct items declared erroneous,
* cost — real reviews and honeypots per item (the volunteers' time),
* reach — share of honest reviewers who qualify as PV,
* lookup share among class-A reviews and how many attackers are flagged.
"""

from __future__ import annotations

import itertools
from collections.abc import Sequence
from dataclasses import dataclass, field, replace

import numpy as np

from dpc.domain.decision import DecisionParams
from dpc.domain.trust import RoleThresholds
from dpc.sim.model import ReviewerType, SimConfig, simulate


@dataclass(frozen=True)
class Grid:
    theta_pv: Sequence[float] = (0.3, 0.45, 0.6)
    honeypot_share: Sequence[float] = (0.05, 0.1, 0.2)
    k_min: Sequence[int] = (2, 3)
    lookup: Sequence[int] = (0, 4)
    seeds: Sequence[int] = (0, 1)
    items: int = 300
    error_rate: float = 0.05
    honest: int = 40
    clickers: int = 4
    extra: dict[str, float] = field(default_factory=dict)


def run_study(grid: Grid) -> list[dict[str, float]]:
    rows = []
    for theta, h, k, lookup in itertools.product(grid.theta_pv, grid.honeypot_share,
                                                 grid.k_min, grid.lookup):
        reviewers = [ReviewerType("honest", grid.honest),
                     ReviewerType("clicker", grid.clickers, behaviour="clicker")]
        if lookup:
            reviewers.append(ReviewerType("lookup", lookup, behaviour="lookup"))
        base = SimConfig(
            items=grid.items, error_rate=grid.error_rate, honeypot_share=h,
            reviewers=tuple(reviewers),
            decision=DecisionParams(prior_error=grid.error_rate, delta_a=1e-3, k_min=k,
                                    max_rounds=4),
            roles=RoleThresholds(theta_pv=theta, theta_pvv=max(theta + 0.25, 0.7)),
        )
        results = [simulate(replace(base, seed=s)) for s in grid.seeds]
        reviews = [r.reviews for r in results]
        lookup_reviews = [r.by_kind.get("lookup", {}).get("reviews", 0.0) for r in results]
        rows.append({
            "theta_pv": theta, "h": h, "k_min": k, "lookup": lookup,
            "miss_rate": float(np.mean([r.miss_rate for r in results])),
            "false_error_rate": float(np.mean([r.false_errors / r.items for r in results])),
            "reviews_per_item": float(np.mean([r.reviews / r.items for r in results])),
            "honeypots_per_item": float(np.mean([r.honeypots_shown / r.items
                                                 for r in results])),
            "escalation_rate": float(np.mean([r.escalated / r.items for r in results])),
            "honest_share_pv": float(np.mean([r.by_kind["honest"]["share_pv"]
                                              for r in results])),
            "lookup_share_of_reviews": float(np.mean(
                [lr / rv if rv else 0.0 for lr, rv in zip(lookup_reviews, reviews, strict=True)]
            )),
            "lookup_flagged": float(np.mean([r.by_kind.get("lookup", {}).get(
                "flagged_suspicious", 0.0) for r in results])),
        })
    return rows


def render_markdown(rows: Sequence[dict[str, float]], grid: Grid) -> str:
    head = (
        "| θ_PV | h | k_min | lookup | miss rate | false err. | reviews/item | "
        "honeypots/item | escal. | honest PV | lookup share | lookup flagged |"
    )
    lines = [
        "# Parameter study (M3)",
        "",
        f"Simulation of class-A review: {grid.items} items, error rate {grid.error_rate}, "
        f"{grid.honest} honest reviewers, {grid.clickers} 'always correct' clickers, "
        f"optionally lookup attackers; δ_A = 0.001; mean over seeds {list(grid.seeds)}.",
        "Generated by `pixi run dpc study`.",
        "",
        head,
        "|" + "---|" * 12,
    ]
    for r in rows:
        lines.append(
            f"| {r['theta_pv']:.2f} | {r['h']:.2f} | {int(r['k_min'])} | {int(r['lookup'])} | "
            f"{r['miss_rate']:.3f} | {r['false_error_rate']:.3f} | {r['reviews_per_item']:.2f} | "
            f"{r['honeypots_per_item']:.2f} | {r['escalation_rate']:.3f} | "
            f"{r['honest_share_pv']:.2f} | {r['lookup_share_of_reviews']:.2f} | "
            f"{r['lookup_flagged']:.2f} |"
        )
    return "\n".join(lines) + "\n"
