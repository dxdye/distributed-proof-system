"""Parameter study for the pilot (M3, concept §18; open decisions OD-5, OD-8).

Sweeps the honeypot share h, the PV threshold θ_PV and k_min, with and without
honeypot lookup attackers, and reports per configuration (mean over seeds):

* miss rate — erroneous items accepted / erroneous items (what δ_A protects),
* false errors — correct items declared erroneous,
* cost — real reviews and honeypots per item (the volunteers' time),
* reach — share of honest reviewers who qualify as PV,
* lookup share among class-A reviews and how many attackers are flagged.
"""

from __future__ import annotations

import itertools
from collections.abc import Sequence
from dataclasses import dataclass, field, replace

import numpy as np

from dpc.domain.decision import DecisionParams
from dpc.domain.trust import RoleThresholds
from dpc.sim.model import ReviewerType, SimConfig, simulate


@dataclass(frozen=True)
class Grid:
    theta_pv: Sequence[float] = (0.3, 0.45, 0.6)
    honeypot_share: Sequence[float] = (0.05, 0.1, 0.2)
    k_min: Sequence[int] = (2, 3)
    lookup: Sequence[int] = (0, 4)
    seeds: Sequence[int] = (0, 1)
    items: int = 300
    error_rate: float = 0.05
    honest: int = 40
    clickers: int = 4
    extra: dict[str, float] = field(default_factory=dict)


def run_study(grid: Grid) -> list[dict[str, float]]:
    rows = []
    for theta, h, k, lookup in itertools.product(grid.theta_pv, grid.honeypot_share,
                                                 grid.k_min, grid.lookup):
        reviewers = [ReviewerType("honest", grid.honest),
                     ReviewerType("clicker", grid.clickers, behaviour="clicker")]
        if lookup:
            reviewers.append(ReviewerType("lookup", lookup, behaviour="lookup"))
        base = SimConfig(
            items=grid.items, error_rate=grid.error_rate, honeypot_share=h,
            reviewers=tuple(reviewers),
            decision=DecisionParams(prior_error=grid.error_rate, delta_a=1e-3, k_min=k,
                                    max_rounds=4),
            roles=RoleThresholds(theta_pv=theta, theta_pvv=max(theta + 0.25, 0.7)),
        )
        results = [simulate(replace(base, seed=s)) for s in grid.seeds]
        reviews = [r.reviews for r in results]
        lookup_reviews = [r.by_kind.get("lookup", {}).get("reviews", 0.0) for r in results]
        rows.append({
            "theta_pv": theta, "h": h, "k_min": k, "lookup": lookup,
            "miss_rate": float(np.mean([r.miss_rate for r in results])),
            "false_error_rate": float(np.mean([r.false_errors / r.items for r in results])),
            "reviews_per_item": float(np.mean([r.reviews / r.items for r in results])),
            "honeypots_per_item": float(np.mean([r.honeypots_shown / r.items
                                                 for r in results])),
            "escalation_rate": float(np.mean([r.escalated / r.items for r in results])),
            "honest_share_pv": float(np.mean([r.by_kind["honest"]["share_pv"]
                                              for r in results])),
            "lookup_share_of_reviews": float(np.mean(
                [lr / rv if rv else 0.0 for lr, rv in zip(lookup_reviews, reviews, strict=True)]
            )),
            "lookup_flagged": float(np.mean([r.by_kind.get("lookup", {}).get(
                "flagged_suspicious", 0.0) for r in results])),
        })
    return rows


def render_markdown(rows: Sequence[dict[str, float]], grid: Grid) -> str:
    head = (
        "| θ_PV | h | k_min | lookup | miss rate | false err. | reviews/item | "
        "honeypots/item | escal. | honest PV | lookup share | lookup flagged |"
    )
    lines = [
        "# Parameter study (M3)",
        "",
        f"Simulation of class-A review: {grid.items} items, error rate {grid.error_rate}, "
        f"{grid.honest} honest reviewers, {grid.clickers} 'always correct' clickers, "
        f"optionally lookup attackers; δ_A = 0.001; mean over seeds {list(grid.seeds)}.",
        "Generated by `pixi run dpc study`.",
        "",
        head,
        "|" + "---|" * 12,
    ]
    for r in rows:
        lines.append(
            f"| {r['theta_pv']:.2f} | {r['h']:.2f} | {int(r['k_min'])} | {int(r['lookup'])} | "
            f"{r['miss_rate']:.3f} | {r['false_error_rate']:.3f} | {r['reviews_per_item']:.2f} | "
            f"{r['honeypots_per_item']:.2f} | {r['escalation_rate']:.3f} | "
            f"{r['honest_share_pv']:.2f} | {r['lookup_share_of_reviews']:.2f} | "
            f"{r['lookup_flagged']:.2f} |"
        )
    return "\n".join(lines) + "\n"


# ------------------------------------------------------------ steering (C-32)
def steering_factor(open_tickets: int, set_size: int, sets_per_take: float) -> float:
    """τ of a determined attacker: it takes its target whenever a set shows it,
    and sees ``sets_per_take`` sets per ticket it takes; an honest reviewer
    picks uniformly from one set. P(attacker takes the target) =
    1 − (1 − n/N)^m against 1/N for an honest reviewer, so τ = N·(1 − (1 − n/N)^m).
    Even m = 1 gives τ = n: choosing is itself a lever."""
    n, big_n = set_size, open_tickets
    return float(big_n * (1.0 - (1.0 - n / big_n) ** sets_per_take))


@dataclass(frozen=True)
class SteeringGrid:
    sybils: Sequence[int] = (2, 5, 10)
    honest: int = 40
    steer: Sequence[float] = (1.0, 4.0, 8.0, 16.0, 26.0, 79.0)
    identity_weight: Sequence[float] = (1.0, 0.5)
    seeds: Sequence[int] = (0, 1, 2, 3, 4)
    items: int = 600
    error_rate: float = 0.1
    target_share: float = 0.5  # share of erroneous items the attacker wants accepted


def run_steering(grid: SteeringGrid) -> list[dict[str, float]]:
    """Target success (erroneous target items accepted) against the miss rate of
    the other erroneous items, which honest misses alone explain."""
    rows = []
    for sybils, steer, weight in itertools.product(grid.sybils, grid.steer,
                                                   grid.identity_weight):
        base = SimConfig(
            items=grid.items, error_rate=grid.error_rate, target_share=grid.target_share,
            reviewers=(ReviewerType("honest", grid.honest),
                       ReviewerType("sybil", sybils, behaviour="sybil")),
            decision=DecisionParams(prior_error=grid.error_rate, delta_a=1e-3, k_min=3,
                                    max_rounds=4),
            steer=steer, weak_identity_weight=weight,
        )
        results = [simulate(replace(base, seed=s)) for s in grid.seeds]
        targets = sum(r.targets for r in results)
        hits = sum(r.targets_accepted for r in results)
        others = sum(r.erroneous - r.targets for r in results)
        other_missed = sum(r.missed - r.targets_accepted for r in results)
        rows.append({
            "sybils": sybils, "steer": steer, "weight": weight,
            "target_success": hits / targets if targets else 0.0,
            "baseline_miss": other_missed / others if others else 0.0,
            "targets": float(targets),
            "reviews_per_item": float(np.mean([r.reviews / r.items for r in results])),
        })
    return rows


def render_steering(rows: Sequence[dict[str, float]], grid: SteeringGrid) -> str:
    lines = [
        "# Steering study (C-32)",
        "",
        f"Simulation of class-A review: {grid.items} items, error rate {grid.error_rate}, "
        f"{grid.honest} honest reviewers and one attacker with s accounts; "
        f"{grid.target_share:.0%} of the erroneous items are the attacker's targets, which "
        "its accounts pass. The accounts gain trust by looking up planted errors (the "
        "worst case of C-07). τ: how much more likely an attacking account is drawn for a "
        "target. Identity weight: the attackers' rates shrunk towards 0.5 in the decision "
        f"rule (1 = full weight). k_min = 3, δ_A = 0.001; pooled over seeds {list(grid.seeds)}.",
        "Generated by `pixi run dpc steering-study`.",
        "",
        "Target success: targets accepted / targets. Baseline: the miss rate of the other "
        "erroneous items in the same runs, i.e. what honest misses alone explain.",
        "",
        "## From the coordinator's limits to τ",
        "",
        "τ = N·(1 − (1 − n/N)^m) for N open tickets, sets of n, and m sets seen per ticket the "
        "attacker takes (`dpc.sim.study.steering_factor`).",
        "",
        "| m (sets seen per take) | τ (N = 200, n = 4) | τ (N = 1000, n = 4) | meaning |",
        "|---|---|---|---|",
    ]
    for m, meaning in ((1, "no rerolling: choosing alone"), (2, "1 unused set per take"),
                       (4, "3 unused sets per take"), (7, "6 unused sets, 1 take a day"),
                       (25, "24 sets a day, 1 take (before C-32)")):
        lines.append(f"| {m} | {steering_factor(200, 4, m):.1f} | "
                     f"{steering_factor(1000, 4, m):.1f} | {meaning} |")
    lines += ["", "## Target success", "",
              "| accounts s | τ | identity weight | target success | baseline miss | targets | "
              "reviews/item |",
              "|---|---|---|---|---|---|---|"]
    for r in rows:
        lines.append(f"| {int(r['sybils'])} | {r['steer']:g} | {r['weight']:g} | "
                     f"{r['target_success']:.2f} | {r['baseline_miss']:.2f} | "
                     f"{int(r['targets'])} | {r['reviews_per_item']:.2f} |")
    return "\n".join(lines) + "\n"
